import { createHash } from 'node:crypto';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { blankQuestion, questionPayload, validateQuestion } from '../../src/lib/questions/questionModel.js';
import { questionBank, seedVersion } from './pilot-question-bank.mjs';

export const seedFile = 'supabase/seeds/coding_questions_pilot_v2.sql';
export const imageRoot = 'public/images/questions/pilot-v2';
export const questionId = key => {
  const bytes = createHash('sha1').update(`${seedVersion}:${key}`).digest().subarray(0,16);
  bytes[6] = (bytes[6] & 15) | 80; bytes[8] = (bytes[8] & 63) | 128;
  const hex = bytes.toString('hex'); return `${hex.slice(0,8)}-${hex.slice(8,12)}-${hex.slice(12,16)}-${hex.slice(16,20)}-${hex.slice(20)}`;
};
export const imageUrl = q => q.diagram ? `/images/questions/pilot-v2/${q.key}.svg` : null;
export function compileQuestions(bank = questionBank) {
  const positions = new Map();
  return bank.map(q => {
    const group = `${q.level}:${q.mode}`;
    const position = (positions.get(group) || 0) % 4; positions.set(group, position + 1);
    const choices = q.options ? q.options.slice(1) : [];
    if (q.options) choices.splice(position, 0, q.options[0]);
    const seconds = { easy:{choice:45,image_choice:60,find_bug:60,block_order:75,scratch_blocks:120}, medium:{choice:60,image_choice:75,find_bug:75,block_order:90,scratch_blocks:150}, hard:{choice:90,image_choice:90,find_bug:90,block_order:120,scratch_blocks:180} }[q.level][q.mode];
    const draft = { ...blankQuestion(), question:q.question, mode:q.mode, difficulty:q.level, category:q.category,
      learning_topic:q.topic, explanation:q.explanation, hint_1:q.hints[0], hint_2:q.hints[1], duration_seconds:seconds,
      blocks:q.blocks || [], code_snippet:q.code || '', bug_line:q.bugLine ?? 0,
      correct_answer:'ABCD'[position], option_a:choices[0] || '', option_b:choices[1] || '', option_c:choices[2] || '', option_d:choices[3] || '',
      ...(q.mode === 'scratch_blocks' ? { block_config:q.config,block_solutions:q.solutions,block_grading:q.grading } : {}),
    };
    const errors = validateQuestion(draft, imageUrl(q));
    if (errors.length) throw new Error(`${q.key}: ${errors.join('; ')}`);
    const payload = { ...questionPayload(draft, imageUrl(q)), id:questionId(q.key), level:q.level };
    // Stable pool order makes regenerating the seed reviewable and reproducible.
    if (q.mode === 'block_order') {
      const pool = q.blocks.map((text,index) => ({text,index,hash:createHash('sha256').update(`${q.key}:${index}`).digest('hex')})).sort((a,b)=>a.hash.localeCompare(b.hash));
      if (pool.every((entry,index)=>entry.index===index)) pool.push(pool.shift());
      payload.blocks = pool.map(e=>e.text); payload.correct_sequence = q.blocks.map((_,i)=>pool.findIndex(e=>e.index===i));
    }
    return { ...q, payload };
  });
}
const jsonLiteral = value => `'${JSON.stringify(value,null,2).replaceAll("'", "''")}'::jsonb`;
export function buildSeedSql(compiled = compileQuestions()) {
  // RETURNING records ONLY newly inserted questions. Existing questions and
  // their private keys, including teacher edits/archives, are never overwritten.
  const rows = compiled.map(q=>({ row:q.payload,solutions:q.solutions || null,grading:q.grading || null }));
  return `-- Generated by npm run seed:questions. Source: scripts/questions/pilot-question-bank.mjs
-- ${seedVersion}: 60 questions, 20 per level, all five authoring modes.
-- Requires existing quiz migrations through 030. Run with the SQL Editor/admin DB connection.
-- Insert only: reruns preserve teacher edits and archived questions. No live battle is changed.
BEGIN;
WITH source AS MATERIALIZED (
 SELECT item, jsonb_populate_record(NULL::public.coding_questions,item->'row') AS q
 FROM jsonb_array_elements(${jsonLiteral(rows)}) AS item
), inserted AS (
 INSERT INTO public.coding_questions(id,question,question_type,image_url,option_a,option_b,option_c,option_d,
 correct_answer,explanation,hint_1,hint_2,category,difficulty,level,is_active,learning_topic,learning_url,
 duration_seconds,blocks,correct_sequence,code_snippet,bug_line,block_config)
 SELECT (q).id,(q).question,(q).question_type,(q).image_url,(q).option_a,(q).option_b,(q).option_c,(q).option_d,
 (q).correct_answer,(q).explanation,(q).hint_1,(q).hint_2,(q).category,(q).difficulty,(q).level,(q).is_active,
 (q).learning_topic,(q).learning_url,(q).duration_seconds,coalesce((q).blocks,'[]'::jsonb),coalesce((q).correct_sequence,'[]'::jsonb),
 (q).code_snippet,(q).bug_line,(q).block_config FROM source
 ON CONFLICT(id) DO NOTHING RETURNING id,question_type
), inserted_keys AS (
 INSERT INTO public.coding_question_block_keys(question_id,solutions,grading)
 SELECT i.id,s.item->'solutions',s.item->'grading' FROM inserted i JOIN source s ON (s.q).id=i.id
 WHERE i.question_type='scratch_blocks' RETURNING question_id
)
SELECT (SELECT count(*) FROM inserted) AS questions_added,
       (SELECT count(*) FROM inserted_keys) AS private_workspace_keys_added;
COMMIT;
`;
}
const escapeXml = s => String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;');
export function codeSvg(q) {
  const { language, code } = q.diagram;
  const lines = code.split('\n'), width = Math.max(720, Math.max(...lines.map(l=>l.length))*16+130), height=126+lines.length*43;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title desc"><title id="title">Kode ${language}</title><desc id="desc">${escapeXml(code)}</desc><rect x="1" y="1" width="${width-2}" height="${height-2}" rx="18" fill="#f5f9fc" stroke="#b7cbdc" stroke-width="2"/><path d="M19 1h${width-38}q18 0 18 18v52H1V19Q1 1 19 1" fill="#163855"/><text x="28" y="45" font-family="Arial,sans-serif" font-weight="700" font-size="24" fill="white">${escapeXml(language)} · baca dari atas ke bawah</text>${lines.map((line,i)=>`<text x="30" y="${112+i*43}" font-family="monospace" font-size="19" fill="#8295a5">${i+1}</text><text x="86" y="${112+i*43}" font-family="monospace" font-size="25" fill="#163855" xml:space="preserve">${escapeXml(line)}</text>`).join('')}</svg>\n`;
}
export async function generateSeed({check=false}={}) {
  const compiled=compileQuestions(),sql=buildSeedSql(compiled);
  if(check) {
    if(await readFile(seedFile,'utf8')!==sql)throw new Error('Seeder SQL tidak sinkron. Jalankan npm run seed:questions.');
    for(const q of compiled.filter(q=>q.diagram?.kind==='code')) if(await readFile(`public${imageUrl(q)}`,'utf8')!==codeSvg(q))throw new Error(`Gambar perlu dibuat ulang: ${q.key}`);
  } else {
    await mkdir(path.dirname(seedFile),{recursive:true}); await mkdir(imageRoot,{recursive:true});
    await writeFile(seedFile,sql);
    for(const q of compiled.filter(q=>q.diagram?.kind==='code'))await writeFile(`public${imageUrl(q)}`,codeSvg(q));
  }
  return compiled;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rows=await generateSeed({check:process.argv.includes('--check')});
  console.log(`${rows.length} soal: Easy 20 / Medium 20 / Hard 20. SQL: ${seedFile}`);
  console.log('Hanya membuat/memeriksa berkas lokal. Tidak mengirim data ke Supabase.');
}
