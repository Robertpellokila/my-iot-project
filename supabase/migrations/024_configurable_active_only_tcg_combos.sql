CREATE OR REPLACE FUNCTION public.tcg_normalize_combo_rule_types()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_input_count integer;
  v_types text[];
BEGIN
  IF NEW.type_keys IS NULL THEN
    RAISE EXCEPTION 'Combo type keys are required.';
  END IF;
  v_input_count := cardinality(NEW.type_keys);
  SELECT array_agg(normalized_type ORDER BY normalized_type)
    INTO v_types
    FROM (
      SELECT public.tcg_canonical_card_type(type_key) AS normalized_type
        FROM unnest(NEW.type_keys) AS source(type_key)
    ) normalized;
  IF v_input_count NOT BETWEEN 2 AND 4 OR coalesce(cardinality(v_types),0) <> v_input_count THEN
    RAISE EXCEPTION 'Combo rules need 2–4 supported TCG types.';
  END IF;
  IF NEW.rule_kind = 'pair' AND (v_input_count <> 2 OR v_types[1] = v_types[2]) THEN
    RAISE EXCEPTION 'A pair rule must contain two different types.';
  ELSIF NEW.rule_kind = 'same' AND (v_input_count <> 2 OR v_types[1] <> v_types[2]) THEN
    RAISE EXCEPTION 'A same-type rule must contain the same type twice.';
  ELSIF NEW.rule_kind = 'triple' AND v_input_count <> 3 THEN
    RAISE EXCEPTION 'A triple rule must contain exactly three types.';
  ELSIF NEW.rule_kind IN ('ultimate','formation') AND v_input_count <> 4 THEN
    RAISE EXCEPTION 'An ultimate or formation rule must contain four types.';
  END IF;
  NEW.type_keys := v_types;
  RETURN NEW;
END;
$function$;

