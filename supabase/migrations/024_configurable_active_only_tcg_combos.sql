CREATE OR REPLACE FUNCTION public.tcg_battle_card_can_attack(
  p_card_id uuid,
  p_turn_index bigint,
  p_max_attacks integer
) RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
  SELECT EXISTS (
    SELECT 1 FROM public.battle_cards c
     WHERE c.id = p_card_id
       AND CASE WHEN coalesce(c.attack_turn_index, -1) = coalesce(p_turn_index, 1)
         THEN coalesce(c.attacks_this_turn, 0) < greatest(1, coalesce(p_max_attacks, 1))
         ELSE true
       END
  );
$function$;

CREATE OR REPLACE FUNCTION public.tcg_apply_combo_status(
  p_battle_id uuid,
  p_source_player text,
  p_source_card_id uuid,
  p_target_card_id uuid,
  p_status_key text,
  p_value integer DEFAULT 0,
  p_metadata jsonb DEFAULT '{}'::jsonb
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_source public.battle_cards%ROWTYPE;
  v_target public.battle_cards%ROWTYPE;
  v_key text := lower(trim(coalesce(p_status_key, '')));
  v_rule jsonb;
  v_max_stacks integer := 1;
BEGIN
  SELECT * INTO v_source FROM public.battle_cards
   WHERE id = p_source_card_id AND battle_id = p_battle_id;
  SELECT * INTO v_target FROM public.battle_cards
   WHERE id = p_target_card_id AND battle_id = p_battle_id FOR UPDATE;
  IF v_source.id IS NULL OR v_target.id IS NULL OR v_key = '' THEN
    RETURN jsonb_build_object('applied', false, 'reason', 'invalid_status_target');
  END IF;

  v_rule := public.tcg_status_rule(v_key);
  v_max_stacks := greatest(1, coalesce((v_rule->>'max_stacks')::integer, 1));
  UPDATE public.battle_status_effects
     SET stacks = least(v_max_stacks, greatest(1, coalesce(stacks, 1) + 1)),
         remaining_turns = 1,
         value = to_jsonb(greatest(0, p_value)),
         metadata = coalesce(metadata, '{}'::jsonb) || coalesce(p_metadata, '{}'::jsonb)
   WHERE battle_id = p_battle_id AND target_card_id = p_target_card_id
     AND lower(status_key) = v_key AND coalesce(active, false);
  IF NOT FOUND THEN
    INSERT INTO public.battle_status_effects (
      battle_id,source_player,source_card_id,target_player,target_card_id,
      scope,status_key,value,stacks,max_stacks,remaining_turns,remaining_rounds,
      consume_on,active,metadata
    ) VALUES (
      p_battle_id,p_source_player,p_source_card_id,v_target.player,p_target_card_id,
      'card',v_key,to_jsonb(greatest(0,p_value)),1,v_max_stacks,1,NULL,
      ARRAY[]::text[],true,
      v_rule || coalesce(p_metadata, '{}'::jsonb) || jsonb_build_object(
        'source_trigger','type_combo','applied_round',coalesce((SELECT round FROM public.battle_sessions WHERE id=p_battle_id),1)
      )
    );
  END IF;

  INSERT INTO public.battle_events (battle_id,type,source_player,target_player,card_id,payload)
  VALUES (p_battle_id,'status_applied',p_source_player,v_target.player,p_source_card_id,
    jsonb_build_object('status_key',v_key,'target_card_id',p_target_card_id,'duration_turns',1,'source_trigger','type_combo'));
  RETURN jsonb_build_object('applied',true,'status_key',v_key,'target_card_id',p_target_card_id,'duration_turns',1);
END;
$function$;

CREATE OR REPLACE FUNCTION public.tcg_submit_active_combo_attack(
  p_code text,
  p_player text,
  p_token text,
  p_primary_card_id uuid,
  p_participant_card_ids uuid[],
  p_target_card_id uuid DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_player text := lower(trim(coalesce(p_player,'')));
  v_enemy text;
  v_guard jsonb;
  v_battle public.battle_sessions%ROWTYPE;
  v_primary public.battle_cards%ROWTYPE;
  v_target public.battle_cards%ROWTYPE;
  v_participant public.battle_cards%ROWTYPE;
  v_participant_id uuid;
  v_rule public.tcg_combo_rule_catalog%ROWTYPE;
  v_participants uuid[] := coalesce(p_participant_card_ids, ARRAY[]::uuid[]);
  v_types text[];
  v_kind text;
  v_cost integer;
  v_ap integer;
  v_ap_after integer;
  v_index integer := 0;
  v_assist integer := 0;
  v_power numeric := 0;
  v_defense integer := 0;
  v_damage integer := 0;
  v_hp_before integer := 0;
  v_hp_after integer := 0;
  v_player_damage integer := 0;
  v_destruction_pct numeric := 0;
  v_heal integer := 0;
  v_shield integer := 0;
  v_destroyed boolean := false;
  v_status jsonb := '{}'::jsonb;
  v_finish jsonb := '{}'::jsonb;
  v_deck_out jsonb := '{}'::jsonb;
  v_action_block text;
  v_response jsonb;
BEGIN
  v_guard := public.tcg_sync_battle_turn(p_code,p_player,p_token);
  IF NOT coalesce((v_guard->>'ok')::boolean,false) THEN RETURN v_guard; END IF;

  SELECT * INTO v_battle FROM public.battle_sessions
   WHERE upper(code)=upper(trim(coalesce(p_code,''))) FOR UPDATE;
  IF NOT FOUND OR v_battle.winner IS NOT NULL OR lower(coalesce(v_battle.status,'')) <> 'battle' THEN
    RETURN jsonb_build_object('ok',false,'message','Battle tidak aktif.');
  END IF;
  IF NOT coalesce(v_battle.action_points_enabled,false) OR lower(coalesce(v_battle.ruleset,'')) <> 'tcg_v1' THEN
    RETURN jsonb_build_object('ok',false,'message','Combo Attack hanya tersedia pada ruleset TCG.');
  END IF;
  IF NOT coalesce(v_battle.combo_enabled,true) THEN
    RETURN jsonb_build_object('ok',false,'message','Combo Attack dinonaktifkan untuk battle ini.');
  END IF;
  IF coalesce(v_battle.question_active,false) OR lower(coalesce(v_battle.status,'')) = 'question' THEN
    RETURN jsonb_build_object('ok',false,'message','Selesaikan kuis sebelum melanjutkan turn.');
  END IF;
  IF v_player NOT IN ('p1','p2') OR lower(coalesce(v_battle.current_turn,'')) <> v_player THEN
    RETURN jsonb_build_object('ok',false,'message','Belum giliran kamu.');
  END IF;
  IF p_primary_card_id IS NULL OR cardinality(v_participants) NOT BETWEEN 2 AND 4
     OR v_participants[1] <> p_primary_card_id
     OR cardinality(v_participants) <> (SELECT count(DISTINCT participant_id) FROM unnest(v_participants) AS ids(participant_id)) THEN
    RETURN jsonb_build_object('ok',false,'message','Pilih 2 sampai 4 kartu Active yang berbeda dan tetapkan kartu utama.');
  END IF;
  IF cardinality(v_participants)=3 AND NOT coalesce(v_battle.triple_combo_enabled,false) THEN
    RETURN jsonb_build_object('ok',false,'message','Triple Combo belum diaktifkan di Game Setup.');
  END IF;
  IF cardinality(v_participants)=4 AND NOT coalesce(v_battle.formation_enabled,false) THEN
    RETURN jsonb_build_object('ok',false,'message','Combo empat kartu memerlukan Formation yang aktif.');
  END IF;

  v_enemy := CASE WHEN v_player='p1' THEN 'p2' ELSE 'p1' END;

  SELECT * INTO v_primary FROM public.battle_cards
   WHERE id=p_primary_card_id AND battle_id=v_battle.id AND player=v_player FOR UPDATE;
  IF NOT FOUND OR v_primary.zone <> 'active' OR coalesce(v_primary.current_hp,v_primary.base_hp,v_primary.hp,0)<=0
     OR coalesce(v_primary.exhausted,false) THEN
    RETURN jsonb_build_object('ok',false,'message','Kartu utama harus berada di Active dan masih hidup.');
  END IF;

  FOREACH v_participant_id IN ARRAY v_participants LOOP
    SELECT * INTO v_participant FROM public.battle_cards
     WHERE id=v_participant_id AND battle_id=v_battle.id AND player=v_player FOR UPDATE;
    IF NOT FOUND OR v_participant.zone <> 'active'
       OR coalesce(v_participant.current_hp,v_participant.base_hp,v_participant.hp,0)<=0
       OR coalesce(v_participant.exhausted,false) THEN
      RETURN jsonb_build_object('ok',false,'message','Semua peserta Combo harus berupa kartu Active yang masih hidup.');
    END IF;
    IF NOT public.tcg_battle_card_can_attack(v_participant.id,v_battle.turn_index,v_battle.max_attacks_per_card) THEN
      RETURN jsonb_build_object('ok',false,'message',v_participant.name || ' sudah memakai kesempatan serangnya pada turn ini.');
    END IF;
    v_action_block := public.tcg_card_action_block_reason(v_battle.id,v_participant.id,'attack');
    IF v_action_block IS NOT NULL THEN RETURN jsonb_build_object('ok',false,'message',v_action_block); END IF;
    v_power := v_power + CASE WHEN v_participant.id=p_primary_card_id
      THEN coalesce(v_participant.attack,0) ELSE 0 END;
  END LOOP;

  SELECT array_agg(t.type_key ORDER BY t.type_key)
    INTO v_types
    FROM unnest(v_participants) WITH ORDINALITY u(card_id,position)
    JOIN public.battle_cards c ON c.id=u.card_id AND c.battle_id=v_battle.id
    CROSS JOIN LATERAL (SELECT public.tcg_canonical_card_type(c.element) AS type_key) t;
  IF coalesce(array_position(v_types,NULL),0)>0 THEN v_types := NULL; END IF;

  v_kind := CASE
    WHEN cardinality(v_participants)=2 AND v_types IS NOT NULL AND v_types[1]=v_types[2] THEN 'same'
    WHEN cardinality(v_participants)=2 THEN 'pair'
    WHEN cardinality(v_participants)=3 THEN 'triple'
    ELSE 'formation'
  END;
  IF v_types IS NOT NULL THEN
    SELECT * INTO v_rule FROM public.tcg_combo_rule_catalog r
     WHERE r.enabled
       AND (r.rule_kind=v_kind OR (v_kind='formation' AND r.rule_kind='ultimate'))
       AND r.type_keys=v_types
     LIMIT 1;
  END IF;
  IF v_rule.id IS NULL THEN
    IF cardinality(v_participants)=2 AND coalesce(v_battle.generic_combo_enabled,false) THEN
      v_rule.combo_name := 'Combined Strike';
      v_rule.assist_multipliers := ARRAY[0.50]::numeric[];
      v_rule.primary_multiplier := 1;
      v_rule.damage_multiplier := 1;
      v_rule.bonus_damage := 0;
      v_rule.defense_ignore_pct := 0;
      v_rule.heal_after := 0;
      v_rule.shield_after := 0;
      v_rule.effect_json := '{"summary":"Serangan bantuan umum tanpa bonus tipe."}'::jsonb;
    ELSE
      RETURN jsonb_build_object('ok',false,'code','COMBO_RULE_MISSING',
        'message',CASE WHEN cardinality(v_participants)=3 THEN 'Kombinasi tiga tipe ini belum memiliki aturan Triple Combo.'
          WHEN cardinality(v_participants)=4 THEN 'Formation ini belum memiliki aturan Ultimate Combo.'
          ELSE 'Kombinasi tipe ini belum terdaftar dan Generic Combo tidak aktif.' END);
    END IF;
  END IF;

  v_cost := CASE
    WHEN cardinality(v_participants)=2 AND coalesce(v_battle.action_costs,'{}'::jsonb) ? 'combo_attack'
      THEN public.tcg_resolve_action_point_cost('combo_attack',v_battle.action_costs)
    WHEN cardinality(v_participants)=3 AND coalesce(v_battle.action_costs,'{}'::jsonb) ? 'triple_combo'
      THEN public.tcg_resolve_action_point_cost('triple_combo',v_battle.action_costs)
    WHEN cardinality(v_participants)=4 AND coalesce(v_battle.action_costs,'{}'::jsonb) ? 'ultimate_combo'
      THEN public.tcg_resolve_action_point_cost('ultimate_combo',v_battle.action_costs)
    ELSE coalesce(v_rule.ap_cost, CASE cardinality(v_participants) WHEN 2 THEN 2 WHEN 3 THEN 3 ELSE 3 END)
  END;
  v_ap := CASE WHEN v_player='p1' THEN coalesce(v_battle.player1_action_points,0)
               ELSE coalesce(v_battle.player2_action_points,0) END;
  IF v_ap < v_cost THEN
    RETURN jsonb_build_object('ok',false,'code','NOT_ENOUGH_ACTION_POINTS',
      'message',format('Combo ini membutuhkan %s AP; tersisa %s AP.',v_cost,v_ap),'action_points',v_ap);
  END IF;
  v_ap_after := v_ap-v_cost;

  v_power := greatest(0,coalesce(v_primary.attack,0) * coalesce(v_rule.primary_multiplier,1));
  v_index := 0;
  FOREACH v_participant_id IN ARRAY v_participants LOOP
    IF v_participant_id <> v_primary.id THEN
      v_index := v_index + 1;
      SELECT * INTO v_participant FROM public.battle_cards WHERE id=v_participant_id AND battle_id=v_battle.id;
      v_assist := floor(greatest(0,coalesce(v_participant.attack,0)) * coalesce(v_rule.assist_multipliers[v_index],CASE WHEN cardinality(v_participants)=2 THEN 0.70 ELSE 0.60 END))::integer;
      v_power := v_power + v_assist;
    END IF;
  END LOOP;
  v_power := (v_power + coalesce(v_rule.bonus_damage,0)) * coalesce(v_rule.damage_multiplier,1);

  SELECT count(*) INTO v_index FROM public.battle_cards c
   WHERE c.battle_id=v_battle.id AND c.player=v_enemy AND c.zone='active'
     AND coalesce(c.current_hp,c.base_hp,c.hp,0)>0 AND NOT coalesce(c.exhausted,false);
  IF p_target_card_id IS NULL AND v_index>0 THEN
    RETURN jsonb_build_object('ok',false,'requires_target',true,'message','Pilih kartu Active lawan sebagai target combo.');
  END IF;
  IF p_target_card_id IS NULL AND NOT coalesce(v_battle.direct_attack_enabled,true) THEN
    RETURN jsonb_build_object('ok',false,'message','Direct Attack dinonaktifkan.');
  END IF;
  IF p_target_card_id IS NOT NULL THEN
    SELECT * INTO v_target FROM public.battle_cards
     WHERE id=p_target_card_id AND battle_id=v_battle.id AND player=v_enemy FOR UPDATE;
    IF NOT FOUND OR v_target.zone<>'active' OR coalesce(v_target.current_hp,v_target.base_hp,v_target.hp,0)<=0
       OR coalesce(v_target.exhausted,false) THEN
      RETURN jsonb_build_object('ok',false,'message','Target harus berupa kartu Active lawan yang masih hidup.');
    END IF;
    v_hp_before := greatest(0,coalesce(v_target.current_hp,v_target.base_hp,v_target.hp,0));
    v_defense := greatest(0,coalesce(v_target.defense,0));
    v_damage := greatest(1,round(v_power)::integer - greatest(0,v_defense-round(v_defense*coalesce(v_rule.defense_ignore_pct,0))::integer));
    v_hp_after := greatest(0,v_hp_before-v_damage);
    v_destroyed := v_hp_after=0;
    IF v_destroyed THEN
      UPDATE public.battle_cards SET current_hp=0,zone='graveyard',exhausted=true,
        destroyed_at=now(),graveyard_at=now(),graveyard_reason='combo_destroyed'
       WHERE id=v_target.id;
      IF coalesce(v_battle.destruction_damage_enabled,true) THEN
        v_destruction_pct := greatest(0,least(1,coalesce(v_battle.destruction_damage_percent,0.30)));
        IF coalesce(v_battle.destruction_damage_mode,'final_damage_percent')='final_damage_percent' THEN
          v_player_damage := round(least(v_hp_before,v_damage)*v_destruction_pct)::integer;
        ELSIF coalesce(v_battle.destruction_damage_mode,'')='overflow_percent' THEN
          v_player_damage := round(greatest(0,v_damage-v_hp_before)*v_destruction_pct)::integer;
        END IF;
      END IF;
      IF v_enemy='p1' THEN
        UPDATE public.battle_sessions SET player1_hp=greatest(0,player1_hp-v_player_damage) WHERE id=v_battle.id;
      ELSE
        UPDATE public.battle_sessions SET player2_hp=greatest(0,player2_hp-v_player_damage) WHERE id=v_battle.id;
      END IF;
    ELSE
      UPDATE public.battle_cards SET current_hp=v_hp_after WHERE id=v_target.id;
    END IF;
  ELSE
    v_damage := greatest(1,round(v_power*0.5)::integer);
    IF v_enemy='p1' THEN
      UPDATE public.battle_sessions SET player1_hp=greatest(0,player1_hp-v_damage) WHERE id=v_battle.id;
    ELSE
      UPDATE public.battle_sessions SET player2_hp=greatest(0,player2_hp-v_damage) WHERE id=v_battle.id;
    END IF;
    v_player_damage := v_damage;
  END IF;

  FOREACH v_participant_id IN ARRAY v_participants LOOP
    UPDATE public.battle_cards
       SET last_attacked_turn=coalesce(v_battle.turn_index,1),
           attacks_this_turn=CASE WHEN coalesce(attack_turn_index,-1)=coalesce(v_battle.turn_index,1)
             THEN coalesce(attacks_this_turn,0)+1 ELSE 1 END,
           attack_turn_index=coalesce(v_battle.turn_index,1)
     WHERE id=v_participant_id AND battle_id=v_battle.id;
  END LOOP;

  v_heal := greatest(0,coalesce(v_rule.heal_after,0));
  v_shield := greatest(0,coalesce(v_rule.shield_after,0));
  IF v_heal>0 THEN
    UPDATE public.battle_cards SET current_hp=least(coalesce(base_hp,hp),coalesce(current_hp,0)+v_heal)
     WHERE id=ANY(v_participants) AND battle_id=v_battle.id AND zone='active';
  END IF;
  IF coalesce(v_battle.status_effects_enabled,true) AND v_shield>0 THEN
    v_status := public.tcg_apply_combo_status(v_battle.id,v_player,v_primary.id,v_primary.id,'shield',v_shield,
      jsonb_build_object('combo_name',v_rule.combo_name,'shield_value',v_shield));
  END IF;
  IF coalesce(v_battle.status_effects_enabled,true) AND v_rule.status_key IS NOT NULL THEN
    IF v_rule.status_target='primary' THEN
      v_status := public.tcg_apply_combo_status(v_battle.id,v_player,v_primary.id,v_primary.id,v_rule.status_key,0,
        jsonb_build_object('combo_name',v_rule.combo_name));
    ELSIF v_rule.status_target='participants' THEN
      v_status := jsonb_build_object('participant_statuses','[]'::jsonb);
      FOREACH v_participant_id IN ARRAY v_participants LOOP
        v_status := jsonb_set(v_status,'{participant_statuses}',
          coalesce(v_status->'participant_statuses','[]'::jsonb) || jsonb_build_array(public.tcg_apply_combo_status(
          v_battle.id,v_player,v_primary.id,v_participant_id,v_rule.status_key,0,
          jsonb_build_object('combo_name',v_rule.combo_name))),true);
      END LOOP;
    ELSIF p_target_card_id IS NOT NULL AND NOT v_destroyed THEN
      v_status := public.tcg_apply_combo_status(v_battle.id,v_player,v_primary.id,p_target_card_id,v_rule.status_key,0,
        jsonb_build_object('combo_name',v_rule.combo_name));
    END IF;
  END IF;
  IF coalesce(v_battle.status_effects_enabled,true)
     AND coalesce((v_rule.effect_json->>'cleanse_negative_status')::boolean,false) THEN
    WITH removed AS (
      UPDATE public.battle_status_effects s
         SET active=false,remaining_turns=0,remaining_rounds=0
       WHERE s.battle_id=v_battle.id AND s.target_card_id=ANY(v_participants)
         AND coalesce(s.active,false)
         AND coalesce(public.tcg_status_rule(s.status_key)->>'kind','') IN ('debuff','control')
       RETURNING s.id
    )
    SELECT count(*)::integer INTO v_index FROM removed;
    v_status := v_status || jsonb_build_object('cleansed_status_count',v_index);
  END IF;

  UPDATE public.battle_sessions SET
    winner=CASE WHEN player1_hp<=0 AND player2_hp<=0 THEN 'draw'
      WHEN player1_hp<=0 THEN 'p2' WHEN player2_hp<=0 THEN 'p1' ELSE winner END,
    status=CASE WHEN player1_hp<=0 OR player2_hp<=0 THEN 'finished' ELSE status END,
    finished_at=CASE WHEN player1_hp<=0 OR player2_hp<=0 THEN now() ELSE finished_at END,
    player1_action_points=CASE WHEN v_player='p1' THEN v_ap_after ELSE player1_action_points END,
    player2_action_points=CASE WHEN v_player='p2' THEN v_ap_after ELSE player2_action_points END
   WHERE id=v_battle.id;

  INSERT INTO public.battle_events (battle_id,type,source_player,target_player,card_id,payload)
  VALUES (v_battle.id,'attack',v_player,v_enemy,v_primary.id,
    jsonb_build_object('ruleset','tcg_v1','attack_mode','active_combo','combo_name',v_rule.combo_name,
      'participant_card_ids',to_jsonb(v_participants),'target_card_id',p_target_card_id,
      'participant_types',coalesce(to_jsonb(v_types),'[]'::jsonb),'ap_cost',v_cost,
      'combo_power',round(v_power)::integer,'damage',v_damage,'target_hp_before',v_hp_before,
      'target_hp_after',v_hp_after,'destroyed',v_destroyed,'player_damage',v_player_damage,
      'healing',v_heal,'shield',v_shield,'status',v_status,
      'message',v_rule.combo_name || ' • ' || v_damage || ' damage'));

  SELECT * INTO v_battle FROM public.battle_sessions WHERE id=v_battle.id;
  IF v_ap_after=0 AND lower(coalesce(v_battle.status,''))<>'finished' THEN
    v_finish := public.tcg_finish_action_point_turn(v_battle.id,v_player);
  END IF;
  v_deck_out := public.tcg_check_battle_deck_out(v_battle.id);
  SELECT * INTO v_battle FROM public.battle_sessions WHERE id=v_battle.id;
  v_response := jsonb_build_object('ok',true,'action','combo_attack','combo_name',v_rule.combo_name,
    'participants',to_jsonb(v_participants),'damage',v_damage,'destroyed',v_destroyed,
    'player_damage',v_player_damage,'healing',v_heal,'status',v_status,
    'action_points',CASE WHEN v_player='p1' THEN v_battle.player1_action_points ELSE v_battle.player2_action_points END,
    'next_turn',v_battle.current_turn,'round',v_battle.round,
    'turn_completed',coalesce((v_finish->>'turn_completed')::boolean,false),
    'deck_out',v_deck_out,'winner',coalesce(v_deck_out->>'winner',v_battle.winner),
    'finished',lower(coalesce(v_battle.status,''))='finished',
    'message',v_rule.combo_name || ' berhasil: ' || v_damage || ' damage.');
  RETURN v_response;
END;
$function$;

