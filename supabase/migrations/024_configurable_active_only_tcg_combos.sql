  SELECT CASE lower(trim(coalesce(p_type, '')))
    WHEN 'electric' THEN 'thunder'
    WHEN 'lightning' THEN 'thunder'
    WHEN 'wind' THEN 'thunder'
    WHEN 'ice' THEN 'water'
    WHEN 'grass' THEN 'forest'
    WHEN 'nature' THEN 'forest'
    WHEN 'holy' THEN 'light'
    WHEN 'warrior' THEN 'knight'
    WHEN 'shadow' THEN 'dark'
    WHEN 'knight' THEN 'knight'
    WHEN 'fire' THEN 'fire'
    WHEN 'water' THEN 'water'
    WHEN 'forest' THEN 'forest'
    WHEN 'thunder' THEN 'thunder'
    WHEN 'light' THEN 'light'
    WHEN 'dark' THEN 'dark'
    ELSE NULL
  END;
$function$;

