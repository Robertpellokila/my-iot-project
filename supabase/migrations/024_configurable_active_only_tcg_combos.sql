CREATE OR REPLACE FUNCTION public.tcg_resolve_action_point_cost(
  p_action text,
  p_costs jsonb DEFAULT '{}'::jsonb
) RETURNS integer
LANGUAGE plpgsql
IMMUTABLE
SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_action text := lower(trim(coalesce(p_action, '')));
  v_key text;
  v_value text;
  v_default integer;
BEGIN
  v_key := CASE v_action
    WHEN 'move_to_bench' THEN 'switch'
    WHEN 'return_from_bench' THEN 'switch'
    WHEN 'switch_active' THEN 'switch'
    ELSE v_action
  END;
  v_default := CASE v_key
    WHEN 'attack' THEN 1
    WHEN 'summon' THEN 1
    WHEN 'switch' THEN 1
    WHEN 'special_skill' THEN 1
    WHEN 'combo_attack' THEN 2
    WHEN 'triple_combo' THEN 3
    WHEN 'fusion' THEN 2
    WHEN 'ultimate_combo' THEN 3
    WHEN 'ultimate' THEN 2
    WHEN 'heal' THEN 1
    WHEN 'synergy' THEN 1
    ELSE 0
  END;
  v_value := coalesce(p_costs->>v_key, '');
  IF v_value ~ '^[0-9]{1,2}$' THEN
    RETURN greatest(0, least(10, v_value::integer));
  END IF;
  RETURN v_default;
END;
$function$;

CREATE OR REPLACE FUNCTION public.tcg_canonical_card_type(p_type text)
RETURNS text
LANGUAGE sql
IMMUTABLE
